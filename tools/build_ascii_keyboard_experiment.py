"""Reproject the locked independent semantic runtime source for keyboard trials.

Pronunciation comes from the locked source database; codes are reconstructed
through the current canonical Pinyin -> Yinyuan chain. The existing production
ASCII dictionaries are never used to infer upstream semantics. This is the
complete source runtime candidate set, not promotion of the curated production
handoff. All output stays in the explicitly selected experiment directory.
"""
from __future__ import annotations

import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import sqlite3
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from yime.canonical_yime_mapping import load_canonical_code_map
from yime.repository_boundary import assert_data_source_allowed
from yime.utils.numeric_pinyin_code import resolve_canonical_code_from_numeric_pinyin
from yime.utils.yinyuan_id_chain import (
    layout_projection_digest, load_disabled_yinyuan_ids,
    load_symbol_to_yinyuan_id, load_yinyuan_id_to_layout_key,
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build(source_database: Path, output: Path, *, limit: int = 0) -> dict:
    source_database = assert_data_source_allowed(source_database, input_id="ascii_keyboard_runtime_source")
    evidence = json.loads((ROOT / "tools/lexicon/handoff/yime_core_fixed.evidence.json").read_text(encoding="utf-8"))
    expected = evidence["provenance"]["runtime_database"]
    identity = {"bytes": source_database.stat().st_size, "sha256": sha256(source_database)}
    if identity != expected:
        raise ValueError("Runtime source identity differs from the approved immutable input")
    output.mkdir(parents=True, exist_ok=True)
    data = output / "data"
    data.mkdir(exist_ok=True)
    completed_manifest = data / "ascii_keyboard_manifest.json"
    # A failed rebuild cannot retain a success manifest for an earlier run.
    if completed_manifest.exists():
        completed_manifest.unlink()
    mapping = load_yinyuan_id_to_layout_key(ROOT)
    disabled = load_disabled_yinyuan_ids(ROOT)
    symbol_ids = load_symbol_to_yinyuan_id(ROOT)
    pinyin_codes = load_canonical_code_map(ROOT)
    counts: Counter[str] = Counter()
    disabled_syllables: Counter[str] = Counter()
    excluded_readings = []
    fixed = output / "canonical_full.dict.yaml"
    connection = sqlite3.connect(source_database.as_uri() + "?mode=ro&immutable=1", uri=True)
    try:
        query = "SELECT text,pinyin_tone,sort_weight FROM runtime_candidates_materialized ORDER BY entry_type,entry_id,pinyin_tone"
        if limit:
            query += " LIMIT " + str(int(limit))
        with fixed.open("w", encoding="utf-8", newline="\n") as stream:
            stream.write("# Generated by the canonical semantic chain; experiment only.\n---\nname: yime_ascii_keyboard_source\nversion: '1'\nsort: by_weight\nuse_preset_vocabulary: false\n...\n")
            for text, pinyin, weight in connection.execute(query):
                counts["source"] += 1
                semantic_code = resolve_canonical_code_from_numeric_pinyin(pinyin_codes, str(pinyin))
                if not semantic_code:
                    raise ValueError(f"Source reading has no canonical encoding: {text!r} {pinyin!r}")
                ids = tuple(symbol_ids[char] for char in semantic_code)
                blocked = set(ids) & disabled
                if blocked:
                    counts["disabled"] += 1
                    disabled_syllables.update(blocked)
                    excluded_readings.append({"text": text, "numeric_pinyin": pinyin,
                                              "disabled_yinyuan_ids": sorted(blocked)})
                    continue
                full = "".join(mapping[item] for item in ids)
                stream.write(f"{text}\t{full}\t{max(0, int(round(weight or 0)))}\n")
                counts["exported"] += 1
                if counts["source"] % 250000 == 0:
                    print(f"Projected {counts['source']} source readings", flush=True)
    finally:
        connection.close()
    subprocess.run([
        "go", "-C", str(ROOT / "go-backend"), "run", "./cmd/yime-lexicon-derive",
        "-input", str(fixed), "-output-dir", str(data),
    ], check=True)
    manifest = {
        "schema_version": 1,
        "scope": "immutable_source_runtime_experiment",
        "production_handoff_promoted": False,
        "layout_projection_sha256": layout_projection_digest(ROOT),
        "disabled_yinyuan_ids": sorted(disabled),
        "source_database": identity,
        "source_reading_count": counts["source"],
        "exported_reading_count": counts["exported"],
        "excluded_disabled_reading_count": counts["disabled"],
        "excluded_id_counts": dict(disabled_syllables),
        "excluded_disabled_readings": excluded_readings,
        "limit": limit,
        "dictionary_sha256": {name: sha256(data / name) for name in (
            "yime_full.dict.yaml", "yime_variable.dict.yaml", "yime_shorthand.dict.yaml")},
    }
    completed_manifest.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(manifest, ensure_ascii=False, indent=2))
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-database", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, default=ROOT / ".generated/ascii-keyboard")
    parser.add_argument("--limit", type=int, default=0)
    args = parser.parse_args()
    if args.limit < 0:
        parser.error("--limit must be nonnegative")
    build(args.source_database, args.output_dir.resolve(), limit=args.limit)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
