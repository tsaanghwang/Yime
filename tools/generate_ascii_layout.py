"""Generate runtime layout metadata from the one editable manual layout.

This command never changes semantic sources or accepts an alternative layout.
The package sidecar is an inventory; active-only consumers must honor its
disabled_yinyuan_ids field. Experimental dictionaries are built separately.
"""
from __future__ import annotations

import argparse
import json
import sys
import subprocess
from itertools import product
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.ascii_keyboard.resolve_layout import build_resolved_layout
from yime.canonical_yime_mapping import load_canonical_code_map
from yime.utils.code_modes import build_code_mode_record, load_ganyin_symbol_metadata
from tools.ascii_keyboard.layout_chain import (
    layout_projection_digest, load_active_yinyuan_id_to_layout_key,
    load_disabled_yinyuan_ids, load_yinyuan_id_to_layout_key,
    load_symbol_to_yinyuan_id,
    load_input_id_to_layout_key, load_erhua_id_to_layout_key, load_erhua_input_registry,
)


def generated_payloads(repo_root: Path = ROOT) -> dict[Path, str]:
    source = repo_root / "prototypes/touch-terminal/encoding/manual_key_layout.json"
    layout = json.loads(source.read_text(encoding="utf-8"))
    symbols = json.loads((repo_root / "internal_data/key_to_symbol.json").read_text(encoding="utf-8"))
    mapping = load_yinyuan_id_to_layout_key(repo_root)
    active = load_active_yinyuan_id_to_layout_key(repo_root)
    input_mapping = load_input_id_to_layout_key(repo_root)
    erhua = load_erhua_input_registry(repo_root)
    metadata = load_ganyin_symbol_metadata(repo_root)
    digest = layout_projection_digest(repo_root)
    payload = {
        "format_version": 1,
        "name": "Yime ASCII concept keyboard experiment",
        "generated_from": "prototypes/touch-terminal/encoding/manual_key_layout.json",
        "layout_projection_sha256": digest,
        "yinyuan_id_to_key": mapping,
        "active_yinyuan_id_to_key": active,
        "input_id_to_key": input_mapping,
        "erhua_id_to_key": load_erhua_id_to_layout_key(repo_root),
        "erhua_input_registry": erhua,
        "input_id_aliases": layout.get("input_id_aliases", {}),
        "disabled_yinyuan_ids": sorted(load_disabled_yinyuan_ids(repo_root)),
    }
    go = [
        "// Code generated by tools/generate_ascii_layout.py; DO NOT EDIT.",
        "package codemode", "",
        "const LayoutVersion = " + json.dumps("ascii-layout-" + digest[:12]),
        "const LayoutProjectionSHA256 = " + json.dumps(digest),
        "const LayoutAlphabet = " + json.dumps("".join(sorted(set(input_mapping.values())))),
        "", "var generatedMusicalMetadata = map[rune]musicalMetadata{",
    ]
    for yinyuan_id, key in sorted(active.items()):
        if not yinyuan_id.startswith("M"):
            continue
        semantic = metadata[symbols[yinyuan_id]]
        quality = int(semantic["quality_group"])
        tone = {"high": 0, "mid": 1, "low": 2}[str(semantic["tone_level"])]
        go.append(f"\t{ord(key)}: {{quality: {quality}, tone: {tone}}}, // {yinyuan_id}")
    next_quality = 1 + max(int(value["quality_group"]) for value in metadata.values())
    families = {family: index + next_quality for index, family in
                enumerate(sorted({unit["quality_family"] for unit in erhua.values()}))}
    for identifier, unit in sorted(erhua.items()):
        quality = families[unit["quality_family"]]
        tone = {"high": 0, "mid": 1, "low": 2}[unit["tone_grade"]]
        go.append(f"\t{ord(input_mapping[identifier])}: {{quality: {quality}, tone: {tone}}}, // {identifier}")
    go.extend(["}", ""])
    algorithm = (repo_root / "go-backend/input_methods/yime/codemode/codemode.go").read_text(encoding="utf-8")
    import re
    algorithm = re.sub(r'\n\tLayoutVersion\s*=.*', '', algorithm)
    algorithm = re.sub(r'\n\tLayoutAlphabet\s*=.*', '', algorithm)
    start = algorithm.index("// Each triple is high")
    end = algorithm.index("func buildLayoutKeySet()", start)
    algorithm = algorithm[:start] + "var musicalByKey = generatedMusicalMetadata\nvar layoutKeySet = buildLayoutKeySet()\n\n" + algorithm[end:]
    start = algorithm.index("func buildMusicalMetadata()")
    end = algorithm.index("// BuildRecord", start)
    algorithm = algorithm[:start] + algorithm[end:]
    algorithm = "// Code generated by tools/generate_ascii_layout.py from the shared algorithm; DO NOT EDIT.\n" + algorithm
    algorithm += "\n" + "\n".join(go[3:])
    go_source = subprocess.run(["gofmt"], input=algorithm, text=True,
                               capture_output=True, check=True).stdout
    symbol_ids = load_symbol_to_yinyuan_id(repo_root)
    disabled = load_disabled_yinyuan_ids(repo_root)
    syllables = []
    excluded = []
    for pinyin, full in sorted(load_canonical_code_map(repo_root).items()):
        ids = [symbol_ids[symbol] for symbol in full]
        if set(ids) & disabled:
            excluded.append(pinyin)
            continue
        modes = build_code_mode_record(full, ganyin_symbol_metadata=metadata)
        project = lambda code: "".join(active[symbol_ids[symbol]] for symbol in code)
        syllables.append({"pinyin": pinyin, "full": project(modes.full_code),
                          "variable": project(modes.variable_code), "shorthand": project(modes.shorthand_code)})
    # Synthetic contraction tests, not admitted syllables or lexicon rows.
    # Metadata comes from the reviewed derived sound registry, not ID ordinals.
    erhua_metadata = {input_mapping[identifier]: {"quality_group": families[unit["quality_family"]],
                                               "tone_level": unit["tone_grade"]}
                      for identifier, unit in erhua.items()}
    erhua_cases = []
    for family in sorted(families):
        keys = sorted(input_mapping[identifier] for identifier, unit in erhua.items()
                      if unit["quality_family"] == family)
        for triple in product(keys, repeat=3):
            full = input_mapping["N01"] + "".join(triple)
            modes = build_code_mode_record(full, ganyin_symbol_metadata=erhua_metadata)
            erhua_cases.append({"family": family, "full": full,
                               "variable": modes.variable_code, "shorthand": modes.shorthand_code})
    return {
        Path("prototypes/touch-terminal/encoding/yime_yinyuan_layout.json"): json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        Path("prototypes/touch-terminal/encoding/manual_key_layout.resolved.json"): json.dumps(build_resolved_layout(layout, symbols), ensure_ascii=False, indent=2) + "\n",
        Path("go-backend/internal/asciicodemode/codemode_generated.go"): go_source,
        Path("go-backend/internal/asciicodemode/testdata/canonical_syllables.json"): json.dumps(
            {"generated_from": "canonical semantic syllables before keyboard projection", "disabled_syllables": excluded,
             "syllables": syllables, "synthetic_erhua_contraction_cases": erhua_cases},
            ensure_ascii=False, indent=2) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for relative, content in generated_payloads().items():
        target = ROOT / relative
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != content:
                stale.append(str(relative))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Stale layout artifacts: " + ", ".join(stale))
        return 1
    print("ASCII layout metadata verified" if args.check else "ASCII layout metadata generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
