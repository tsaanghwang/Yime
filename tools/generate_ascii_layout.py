"""Generate runtime layout metadata from the one editable manual layout.

This command never changes semantic sources or accepts an alternative layout.
The package sidecar is an inventory; active-only consumers must honor its
disabled_yinyuan_ids field. Experimental dictionaries are built separately.
"""
from __future__ import annotations

import argparse
import json
import sys
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools.resolve_manual_key_layout import build_resolved_layout
from yime.canonical_yime_mapping import load_canonical_code_map
from yime.utils.code_modes import build_code_mode_record, load_ganyin_symbol_metadata
from yime.utils.yinyuan_id_chain import (
    layout_projection_digest, load_active_yinyuan_id_to_layout_key,
    load_disabled_yinyuan_ids, load_yinyuan_id_to_layout_key,
    load_symbol_to_yinyuan_id,
)


def generated_payloads(repo_root: Path = ROOT) -> dict[Path, str]:
    source = repo_root / "internal_data/manual_key_layout.json"
    layout = json.loads(source.read_text(encoding="utf-8"))
    symbols = json.loads((repo_root / "internal_data/key_to_symbol.json").read_text(encoding="utf-8"))
    mapping = load_yinyuan_id_to_layout_key(repo_root)
    active = load_active_yinyuan_id_to_layout_key(repo_root)
    metadata = load_ganyin_symbol_metadata(repo_root)
    digest = layout_projection_digest(repo_root)
    payload = {
        "format_version": 1,
        "name": "Yime ASCII concept keyboard experiment",
        "generated_from": "internal_data/manual_key_layout.json",
        "layout_projection_sha256": digest,
        "yinyuan_id_to_key": mapping,
        "active_yinyuan_id_to_key": active,
        "disabled_yinyuan_ids": sorted(load_disabled_yinyuan_ids(repo_root)),
    }
    go = [
        "// Code generated by tools/generate_ascii_layout.py; DO NOT EDIT.",
        "package codemode", "",
        "const LayoutVersion = " + json.dumps("ascii-layout-" + digest[:12]),
        "const LayoutAlphabet = " + json.dumps("".join(sorted(set(active.values())))),
        "", "var generatedMusicalMetadata = map[rune]musicalMetadata{",
    ]
    for yinyuan_id, key in sorted(active.items()):
        if not yinyuan_id.startswith("M"):
            continue
        semantic = metadata[symbols[yinyuan_id]]
        quality = int(semantic["quality_group"])
        tone = {"high": 0, "mid": 1, "low": 2}[str(semantic["tone_level"])]
        go.append(f"\t{ord(key)}: {{quality: {quality}, tone: {tone}}}, // {yinyuan_id}")
    go.extend(["}", ""])
    go_source = subprocess.run(["gofmt"], input="\n".join(go), text=True,
                               capture_output=True, check=True).stdout
    symbol_ids = load_symbol_to_yinyuan_id(repo_root)
    disabled = load_disabled_yinyuan_ids(repo_root)
    syllables = []
    excluded = []
    for pinyin, full in sorted(load_canonical_code_map(repo_root).items()):
        ids = [symbol_ids[symbol] for symbol in full]
        if set(ids) & disabled:
            excluded.append(pinyin)
            continue
        modes = build_code_mode_record(full, ganyin_symbol_metadata=metadata)
        project = lambda code: "".join(active[symbol_ids[symbol]] for symbol in code)
        syllables.append({"pinyin": pinyin, "full": project(modes.full_code),
                          "variable": project(modes.variable_code), "shorthand": project(modes.shorthand_code)})
    return {
        Path("go-backend/input_methods/yime/data/yime_yinyuan_layout.json"): json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        Path("internal_data/manual_key_layout.resolved.json"): json.dumps(build_resolved_layout(layout, symbols), ensure_ascii=False, indent=2) + "\n",
        Path("go-backend/input_methods/yime/codemode/layout_generated.go"): go_source,
        Path("go-backend/input_methods/yime/codemode/testdata/canonical_syllables.json"): json.dumps(
            {"generated_from": "canonical semantic syllables before keyboard projection", "disabled_syllables": excluded, "syllables": syllables},
            ensure_ascii=False, indent=2) + "\n",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for relative, content in generated_payloads().items():
        target = ROOT / relative
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != content:
                stale.append(str(relative))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
    if stale:
        print("Stale layout artifacts: " + ", ".join(stale))
        return 1
    print("ASCII layout metadata verified" if args.check else "ASCII layout metadata generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
